import type { Feature } from '@space/content-contracts';

// HUD ids match HudModule.getId(); game ids encode GameplayModule enum names
// as game-<lowercase-kebab-case> because the public DTO requires slug-safe ids.
const createModule = (
  id: string,
  name: string,
  summary: string,
  details: string,
  category: Feature['category'],
): Feature => ({ id, slug: id, name, summary, details, category, status: 'prototype' });
const hud = (id: string, name: string, summary: string, details: string) =>
  createModule(id, name, summary, details, 'hud');
const game = (
  id: string,
  name: string,
  summary: string,
  details: string,
  category: Feature['category'] = 'comfort',
) => createModule(`game-${id}`, name, summary, details, category);

